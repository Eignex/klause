package com.eignex.klause.bench.metric

import com.eignex.klause.bench.catalog.Format
import org.junit.jupiter.params.ParameterizedTest
import org.junit.jupiter.params.provider.ValueSource
import java.nio.file.Files
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull
import kotlin.test.assertNotEquals

class SolveEvidenceTest {
    @Test
    fun `compiled content ignores only generated path header comments`() {
        val root = Files.createTempDirectory("compiled-content-").toFile()
        try {
            fun source(name: String, path: String, body: String = "var 1..2: x;\n") = root.resolve(name).apply {
                writeText("% Generated by MiniZinc 2.10.1\n% Solver library: $path\n% Command line invocation: $path/tmp.fzn\n$body")
            }
            val first = source("first.fzn", "/first")
            val relocated = source("relocated.fzn", "/second")
            val changed = source("changed.fzn", "/second", "var 1..3: x;\n")

            assertEquals(SolveEvidence.flatZincContentHash(first), SolveEvidence.flatZincContentHash(relocated))
            assertNotEquals(SolveEvidence.flatZincContentHash(first), SolveEvidence.flatZincContentHash(changed))
            assertNotEquals(SolveEvidence.fileHashes(mapOf("raw" to first)), SolveEvidence.fileHashes(mapOf("raw" to relocated)))
        } finally {
            root.deleteRecursively()
        }
    }

    @Test
    fun `ordinary compiled text retains its exact byte identity`() {
        val file = Files.createTempFile("compiled-text-", ".fzn").toFile()
        try {
            file.writeText("string: x = \"% Command line invocation: source\";\r\nsolve satisfy;\r\n")

            assertEquals(SolveEvidence.fileHashes(mapOf("raw" to file))["raw"], SolveEvidence.flatZincContentHash(file))
        } finally {
            file.delete()
        }
    }

    @Test
    fun `compiled identities follow bytes independently of artifact paths`() {
        val root = Files.createTempDirectory("compiled-identities-").toFile()
        try {
            val first = root.resolve("first.fzn").apply { writeText("abc") }
            val relocated = root.resolve("second.fzn").apply { writeText("abc") }
            val mapping = root.resolve("output.ozn").apply { writeText("") }

            val hashes = SolveEvidence.fileHashes(mapOf("flatzinc" to first, "outputMapping" to mapping))

            assertEquals("ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad", hashes["flatzinc"])
            assertEquals(hashes["flatzinc"], SolveEvidence.fileHashes(mapOf("flatzinc" to relocated))["flatzinc"])
            assertEquals("e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855", hashes["outputMapping"])
        } finally {
            root.deleteRecursively()
        }
    }

    @Test
    fun `only the last complete minizinc candidate should be retained`() {
        val raw = "x = 1;\n----------\nx = 2;\n----------\nx = 3;\n"

        val witness = SolveEvidence.finalWitness(Format.MINIZINC, raw)

        assertEquals("x = 2;", witness)
    }

    @Test
    fun `competition records should retain the final rendered witness`() {
        for (format in listOf(Format.OPB, Format.DIMACS, Format.WCNF, Format.MPS)) {
            val witness = SolveEvidence.finalWitness(format, "v x1\no 2\nv -x1 x2\nc solveTime=1\n")

            assertEquals("v -x1 x2", witness)
        }
    }

    @Test
    fun `an empty OPB assignment should be retained`() {
        val witness = SolveEvidence.finalWitness(Format.OPB, "s SATISFIABLE\nv\nc solutions=1\n")

        assertEquals("v", witness)
    }

    @Test
    fun `a stream without a complete candidate should carry no witness`() {
        for (format in listOf(Format.MINIZINC, Format.OPB, Format.XCSP3)) {
            assertNull(SolveEvidence.finalWitness(format, "=====UNKNOWN=====\n"))
        }
    }

    @Test
    fun `SMT feasible verdicts should retain only the exact rendered model`() {
        val model = """
            (
              (define-fun wide () Int 18446744073709551616)
              (define-fun negative () Int (- 18446744073709551616))
              (define-fun fraction () Real (- (/ 2.0 3.0)))
              (define-fun whole () Real 5.0)
              (define-fun |flag ()| () Bool true)
            )
        """.trimIndent()
        for (status in listOf(null, "optimal", "best-found", "unbounded")) {
            val metadata = status?.let { "; objective=-2/3\nsat\n; optimizationStatus=$it\n" } ?: "sat\n"
            val raw = "$metadata$model\n; solveTime=0.01\n; solutions=1\n"

            val witness = SolveEvidence.finalWitness(Format.SMTLIB, raw)

            assertEquals(model, witness, status)
        }
    }

    @Test
    fun `only the last complete SMT model should be retained`() {
        val model = "(\n  (define-fun x () Int 2)\n)"
        val raw = "sat\n(\n  (define-fun x () Int 1)\n)\nsat\n$model\n(\n  (define-fun x () Int 3)\n"

        val witness = SolveEvidence.finalWitness(Format.SMTLIB, raw)

        assertEquals(model, witness)
    }

    @Test
    fun `model free SMT results should carry no witness`() {
        for (raw in listOf("", "unsat\n", "unknown\n", "sat\n", "; objective=7\n; optimizationStatus=optimal\n")) {
            assertNull(SolveEvidence.finalWitness(Format.SMTLIB, raw), raw)
        }
    }

    @Test
    fun `an incomplete SMT model should carry no witness`() {
        val raw = "sat\n(\n  (define-fun x () Real (/ 1.0 3.0))\n"

        val witness = SolveEvidence.finalWitness(Format.SMTLIB, raw)

        assertNull(witness)
    }

    @Test
    fun `an empty SMT model should be retained`() {
        val witness = SolveEvidence.finalWitness(Format.SMTLIB, "sat\n(\n)\n; solveTime=0.01\n")

        assertEquals("(\n)", witness)
    }

    @ParameterizedTest
    @ValueSource(strings = ["LF", "CR", "CRLF"])
    fun `SMT line endings should preserve blank lines in the last complete model`(ending: String) {
        val separator = when (ending) {
            "CR" -> "\r"
            "CRLF" -> "\r\n"
            else -> "\n"
        }
        val raw = listOf(
            "", "sat", "(", ")", "(", "", "", "  (define-fun |wide é𝄞| () Int 2)", "", ")",
            "", "", "(", "  (define-fun x () Int 3)", "",
        ).joinToString(separator)

        val witness = SolveEvidence.finalWitness(Format.SMTLIB, raw)

        assertEquals("(\n\n\n  (define-fun |wide é𝄞| () Int 2)\n\n)", witness)
    }

    @Test
    fun `a restarted SMT model should discard its incomplete prefix`() {
        val raw = "sat\n(\n  discarded\n(\n  (define-fun x () Int 2)\n)\n"

        val witness = SolveEvidence.finalWitness(Format.SMTLIB, raw)

        assertEquals("(\n  (define-fun x () Int 2)\n)", witness)
    }

    @Test
    fun `SMT model delimiters should require standalone lines`() {
        val raw = "sat\n (\n)\n(\n( \n )\n) \n)\n"

        val witness = SolveEvidence.finalWitness(Format.SMTLIB, raw)

        assertEquals("(\n( \n )\n) \n)", witness)
    }

    @Test
    fun `an unmatched SMT closing line should retain the completed model`() {
        val raw = "sat\n(\n  (define-fun x () Int 2)\n)\n)\n"

        val witness = SolveEvidence.finalWitness(Format.SMTLIB, raw)

        assertEquals("(\n  (define-fun x () Int 2)\n)", witness)
    }

    @ParameterizedTest
    @ValueSource(strings = ["", "1"])
    fun `SMT witness size should be limited by the complete model length`(extra: String) {
        val prefix = "(\n  (define-fun x () Int "
        val suffix = ")\n)"
        val digits = "1".repeat(8 * 1024 * 1024 - prefix.length - suffix.length)
        val model = "$prefix$digits$extra$suffix"
        val raw = "sat\n(\n)\n$model\n"

        val witness = SolveEvidence.finalWitness(Format.SMTLIB, raw)

        assertEquals(if (extra.isEmpty()) model else null, witness)
    }

    @Test
    fun `MiniZinc witnesses should keep the final solution and its klause comment lines byte for byte`() {
        val raw = "% started\nx = 1;\n----------\n" +
            "% klause-exact: x = 3/2;\n  x = 2;\n% note\ny = [1, 2];\n" +
            "% klause-coordinate: X_INTRODUCED_4_ = 7;\n% klause-float-grid: 0.5\n_objective = 3;\n" +
            "----------\n==========\n% solveTime=0.1\n"

        val witness = SolveEvidence.finalWitness(Format.MINIZINC, raw)

        assertEquals(
            "  x = 2;\ny = [1, 2];\n_objective = 3;\n" +
                "% klause-exact: x = 3/2;\n% klause-coordinate: X_INTRODUCED_4_ = 7;\n% klause-float-grid: 0.5",
            witness,
        )
    }

    @Test
    fun `model reconstruction should preserve the final complete assignment frame`() {
        val raw = "x = 1;\n% klause-assignment: hidden = 2;\n----------\n" +
            "x = 7;\n% klause-assignment-begin: flatzinc-integer-v1\n" +
            "% klause-assignment: hidden = 14;\n% klause-assignment-end\n----------\n"

        val witness = SolveEvidence.finalWitness(Format.MINIZINC, raw) { "model_x = 7;" }

        assertEquals("model_x = 7;\n% klause-assignment-begin: flatzinc-integer-v1\n" +
            "% klause-assignment: hidden = 14;\n% klause-assignment-end", witness)
    }

    @Test
    fun `a MiniZinc solution of exact coordinates alone should keep only those lines`() {
        val raw = "% klause-exact: x = 1/3;\n% klause-coordinate: y = 2;\n----------\n"

        val witness = SolveEvidence.finalWitness(Format.MINIZINC, raw)

        assertEquals("\n% klause-exact: x = 1/3;\n% klause-coordinate: y = 2;", witness)
    }

    @Test
    fun `a MiniZinc solution should start at its first assignment line`() {
        val raw = "noise line\nx = [\n  1, 2\n];\n=====UNSAT=====\n----------\n"

        val witness = SolveEvidence.finalWitness(Format.MINIZINC, raw)

        assertEquals("x = [\n  1, 2\n];", witness)
    }

    @Test
    fun `a model output mapping should replace the final MiniZinc solution and keep its klause comment lines`() {
        val raw = "x = 1;\n----------\nX_INTRODUCED_3_ = [1, 2];\n% klause-float-component: none\n----------\n"
        val seen = mutableListOf<String>()

        val witness = SolveEvidence.finalWitness(Format.MINIZINC, raw) { flat ->
            seen += flat
            "c = [Red, Green];"
        }

        assertEquals(listOf("X_INTRODUCED_3_ = [1, 2];"), seen)
        assertEquals("c = [Red, Green];\n% klause-float-component: none", witness)
    }

    @Test
    fun `an exact coordinate only MiniZinc solution should not reach the model output mapping`() {
        val raw = "% klause-exact: x = 1/3;\n----------\n"

        val witness = SolveEvidence.finalWitness(Format.MINIZINC, raw) { error("no solution to map") }

        assertEquals("\n% klause-exact: x = 1/3;", witness)
    }

    @Test
    fun `XCSP3 witnesses should keep the last complete instantiation with one v prefix`() {
        val raw = "v <instantiation><list>x</list><values>1</values></instantiation>\no 4\n" +
            "v <instantiation type='solution' cost='3'>\nv   <list> x y </list>\n" +
            "v   <values> 1 2 </values>\nv </instantiation>\ns OPTIMUM FOUND\n"

        val witness = SolveEvidence.finalWitness(Format.XCSP3, raw)

        assertEquals(
            "v <instantiation type='solution' cost='3'>\n  <list> x y </list>\n  <values> 1 2 </values>\n" +
                "</instantiation>",
            witness,
        )
    }

    @Test
    fun `an unterminated XCSP3 instantiation should carry no witness`() {
        val raw = "v <instantiation>\nv <list>x</list>\n"

        assertNull(SolveEvidence.finalWitness(Format.XCSP3, raw))
    }

    @Test
    fun `only the last complete XCSP3 instantiation should be retained`() {
        val model = "<instantiation><list>x</list><values>2</values></instantiation>"
        val raw = "v <instantiation><list>x</list><values>1</values></instantiation>\n" +
            "v $model\nv <instantiation>\nv <list>x</list>\n"

        val witness = SolveEvidence.finalWitness(Format.XCSP3, raw)

        assertEquals("v $model", witness)
    }
}
