#!/usr/bin/env bash
set -euo pipefail
: "${LAB_WORKTREE:?lab source root is required}"
: "${OUT:?lab output directory is required}"
request="${1:?a compiler comparison JSON request is required}"
command -v jq >/dev/null
if command -v sha256sum >/dev/null; then
  digest() { sha256sum "$@"; }
else
  command -v shasum >/dev/null
  digest() { shasum -a 256 "$@"; }
fi
if command -v timeout >/dev/null; then tool_timer=$(command -v timeout)
else tool_timer=$(command -v gtimeout); fi
jq -e '
  .schema == "minizinc-input-comparison-v1" and .compilerSeed == 1 and
  .toolTimeoutSeconds == 60 and (.repeats | IN(2,4,6,8)) and
  (.sources | length >= 1 and length <= 8) and (.compilers | length == 2) and
  all(.compilers[]; (.name | test("^[A-Za-z0-9_-]+$")) and
    (.executableSha256 | test("^[0-9a-f]{64}$")) and
    (.standardLibrarySha256 | test("^[0-9a-f]{64}$"))) and
  all(.sources[]; (.model.text | type == "string") and (.data.text | type == "string") and
    (.model.sha256 | test("^[0-9a-f]{64}$")) and (.data.sha256 | test("^[0-9a-f]{64}$")))
' <<< "$request" >/dev/null
mkdir -p "$OUT"
output="$OUT/minizinc-input-comparison"
mkdir "$output"
printf '%s' "$request" > "$output/request.json"
git -C "$LAB_WORKTREE" rev-parse HEAD > "$output/revision.txt"
uname -a > "$output/platform.txt"
"$tool_timer" --version > "$output/timer-version.txt"
printf '%s\n' "$tool_timer" > "$output/timer-path.txt"
digest "$tool_timer" > "$output/timer.sha256"
resolve_path() {
  case "$1" in
    /*) printf '%s\n' "$1" ;;
    *) [[ "$1" != .. && "$1" != ../* && "$1" != */../* && "$1" != */.. ]]
       printf '%s/%s\n' "$LAB_WORKTREE" "$1" ;;
  esac
}
expect_file() {
  if [[ "$(digest "$1" | cut -d ' ' -f 1)" != "$2" ]]; then
    printf 'SHA-256 mismatch: %s\n' "$1" >&2
    return 1
  fi
}
tree_hash() {
  local tree_root="$1" tree_file
  find -L "$tree_root" -type f | LC_ALL=C sort | while IFS= read -r tree_file; do
    printf '%s\0' "${tree_file#"$tree_root"/}"
    cat "$tree_file"
    printf '\0'
  done | digest | cut -d ' ' -f 1
}
fzn_content_v1() {
  local version_line library_line command_line
  {
    IFS= read -r version_line
    IFS= read -r library_line
    IFS= read -r command_line
    [[ "$version_line" == '% Generated by MiniZinc '* && "$library_line" == '% Solver library: '* &&
      "$command_line" == '% Command line invocation: '* ]]
    printf '%s\n\n\n' "$version_line"
    cat
  } < "$1"
}
run_tool() {
  local tool_output="$1" tool_exit=0
  shift
  jq -n --args '$ARGS.positional' -- "$@" > "$tool_output.command.json"
  TIMEFORMAT=$'real=%R\nuser=%U\nsystem=%S'
  { time "$tool_timer" -s KILL 60 "$@" < /dev/null > "$tool_output.stdout" 2> "$tool_output.stderr"; } \
    2> "$tool_output.resources.txt" || tool_exit=$?
  printf '%s\n' "$tool_exit" > "$tool_output.exit"
  return "$tool_exit"
}
solver_library="$LAB_WORKTREE/klause-mzn-lib/share/minizinc/klause"
configuration="$LAB_WORKTREE/klause-mzn-lib/share/minizinc/solvers/klause.msc"
test "$(tree_hash "$solver_library")" = "$(jq -er .solverLibrarySha256 <<< "$request")"
expect_file "$configuration" "$(jq -er .configurationSha256 <<< "$request")"
mkdir "$output/compilers" "$output/inputs"
for compiler_index in 0 1; do
  compiler=$(resolve_path "$(jq -er ".compilers[$compiler_index].executable" <<< "$request")")
  standard=$(resolve_path "$(jq -er ".compilers[$compiler_index].standardLibrary" <<< "$request")")
  standard=$(cd "$standard" && pwd -P)
  test -x "$compiler"
  expect_file "$compiler" "$(jq -er ".compilers[$compiler_index].executableSha256" <<< "$request")"
  compiler_executables[$compiler_index]="$compiler"
  compiler_libraries[$compiler_index]="$standard"
  metadata="$output/compilers/$compiler_index"
  mkdir "$metadata"
  printf 'LC_ALL=C\nMZN_STDLIB_DIR=%s\n' "$standard" > "$metadata/environment.txt"
  for environment_key in PATH LANG LC_NUMERIC MZN_SOLVER_PATH MZN_USER_CONFIG_DIR \
    DYLD_LIBRARY_PATH DYLD_INSERT_LIBRARIES DYLD_FRAMEWORK_PATH DYLD_FALLBACK_LIBRARY_PATH LD_LIBRARY_PATH; do
    printf '%s=' "$environment_key" >> "$metadata/environment.txt"
    printenv "$environment_key" >> "$metadata/environment.txt" || printf '<unset>\n' >> "$metadata/environment.txt"
  done
  if command -v otool >/dev/null; then
    otool -L "$compiler" > "$metadata/linked-libraries.txt"
  else
    printf 'linked-library inspection unavailable\n' > "$metadata/linked-libraries-unavailable.txt"
  fi
  run_tool "$metadata/version" env LC_ALL=C "MZN_STDLIB_DIR=$standard" "$compiler" --version
  run_tool "$metadata/config-dirs" env LC_ALL=C "MZN_STDLIB_DIR=$standard" "$compiler" --config-dirs
  actual_standard=$(jq -er .mznStdlibDir "$metadata/config-dirs.stdout")
  test "$(cd "$actual_standard" && pwd -P)" = "$standard"
  tree_hash "$standard" > "$metadata/library-before.sha256"
  test "$(cat "$metadata/library-before.sha256")" = \
    "$(jq -er ".compilers[$compiler_index].standardLibrarySha256" <<< "$request")"
done
source_count=$(jq '.sources | length' <<< "$request")
repeats=$(jq .repeats <<< "$request")
failed=0
printf 'source\trepeat\tcompiler\texit\n' > "$output/compilations.tsv"
printf 'source\trepeat\tfznContentV1Equal\toutputMappingEqual\n' > "$output/comparisons.tsv"
for ((source_index=0; source_index<source_count; source_index++)); do
  source_dir="$output/inputs/$source_index"
  mkdir "$source_dir"
  jq -j ".sources[$source_index].model.text" <<< "$request" > "$source_dir/source.mzn"
  jq -j ".sources[$source_index].data.text" <<< "$request" > "$source_dir/source.dzn"
  expect_file "$source_dir/source.mzn" "$(jq -er ".sources[$source_index].model.sha256" <<< "$request")"
  expect_file "$source_dir/source.dzn" "$(jq -er ".sources[$source_index].data.sha256" <<< "$request")"
  for ((repetition=0; repetition<repeats; repetition++)); do
    for position in 0 1; do
      compiler_index=$(((repetition + position) % 2))
      target="$output/source-$source_index-repeat-$repetition-compiler-$compiler_index"
      mkdir "$target"
      compile_exit=0
      run_tool "$target/compile" env LC_ALL=C "MZN_STDLIB_DIR=${compiler_libraries[$compiler_index]}" \
        "${compiler_executables[$compiler_index]}" --solver "$configuration" -c --output-mode dzn \
        --output-objective --output-ozn-to-file "$target/model.ozn" --random-seed 1 -G "$solver_library" \
        --output-fzn-to-file "$target/model.fzn" -I "$source_dir" "$source_dir/source.mzn" \
        "$source_dir/source.dzn" || compile_exit=$?
      if [[ "$compile_exit" -ne 0 || ! -s "$target/model.fzn" || ! -s "$target/model.ozn" ]]; then
        failed=1
      else
        fzn_content_v1 "$target/model.fzn" | digest | cut -d ' ' -f 1 > "$target/fzn-content-v1.sha256"
        digest "$target/model.ozn" | cut -d ' ' -f 1 > "$target/output-mapping.sha256"
      fi
      printf '%s\t%s\t%s\t%s\n' "$source_index" "$repetition" "$compiler_index" "$compile_exit" \
        >> "$output/compilations.tsv"
    done
    left="$output/source-$source_index-repeat-$repetition-compiler-0"
    right="$output/source-$source_index-repeat-$repetition-compiler-1"
    fzn_equal=unknown
    ozn_equal=unknown
    if [[ -s "$left/fzn-content-v1.sha256" && -s "$right/fzn-content-v1.sha256" ]]; then
      fzn_equal=false; ozn_equal=false
      if cmp -s "$left/fzn-content-v1.sha256" "$right/fzn-content-v1.sha256"; then fzn_equal=true; fi
      if cmp -s "$left/output-mapping.sha256" "$right/output-mapping.sha256"; then ozn_equal=true; fi
    fi
    printf '%s\t%s\t%s\t%s\n' "$source_index" "$repetition" "$fzn_equal" "$ozn_equal" \
      >> "$output/comparisons.tsv"
  done
  expect_file "$source_dir/source.mzn" "$(jq -er ".sources[$source_index].model.sha256" <<< "$request")"
  expect_file "$source_dir/source.dzn" "$(jq -er ".sources[$source_index].data.sha256" <<< "$request")"
done
for compiler_index in 0 1; do
  expect_file "${compiler_executables[$compiler_index]}" \
    "$(jq -er ".compilers[$compiler_index].executableSha256" <<< "$request")"
  tree_hash "${compiler_libraries[$compiler_index]}" > "$output/compilers/$compiler_index/library-after.sha256"
  cmp "$output/compilers/$compiler_index/library-before.sha256" \
    "$output/compilers/$compiler_index/library-after.sha256"
done
test "$(tree_hash "$solver_library")" = "$(jq -er .solverLibrarySha256 <<< "$request")"
expect_file "$configuration" "$(jq -er .configurationSha256 <<< "$request")"
exit "$failed"
